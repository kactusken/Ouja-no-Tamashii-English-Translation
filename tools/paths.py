"""Where everything lives. Every tool imports its paths from here.

Default layout, relative to the project folder (the folder that contains tools/):

    original-game/            the Japanese disc image you provide (.bin/.cue)
    translation/              everything that is edited by hand
        text/                 in-game text tables (PROG.csv, STAFF.csv, CRW.csv)
        graphics.csv          every image with Japanese text: transcription, English, status
        glossary.md           names and terms
        images-handmade/      hand-edited images - highest priority at build time (game art - not in git)
        images-approved/      reviewed automatic renders, frozen (game art - not in git)
    output/                   the translated disc image(s) to play
    review/                   things to look at - regenerated by the tools
        images-japanese/      every original image (PNG + .json the tools need)
        images-english/       every final English image, exactly as built
        compare/              side-by-side Japanese | English sheets
        contact-sheets/       contact sheets of the original images
        edit/                 reference images written by edit.py
    tools/  docs/
    cache/                    internal working files - safe to delete

Every location can be moved with the folder options below (see FOLDER_HELP); tools that use these
folders accept them on the command line. Relative paths are taken from the current directory.
"""
import argparse
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
ORIGINAL_NAME = 'Zen Nihon Pro Wres - Ouja no Tamashii (Japan).bin'
ORIGINAL_SHA1 = '1bc41b753496de3487538a68bbf49714001d7f03'
ARCHIVE = 'DATALINK'                        # the archive all translated images live in

FOLDER_HELP = '''folder options (defaults are relative to --root, which defaults to the project folder):
  --root DIR          base folder for every default below
  --original PATH     the Japanese .bin, or a folder holding it    (original-game/)
  --translation DIR   text/, graphics.csv, images-handmade/, images-approved/    (translation/)
  --output DIR        where the translated disc image is written    (output/)
  --review DIR        regenerated pictures to look at    (review/)
  --cache DIR         internal working files    (cache/)'''


def _set(root=PROJECT, original=None, translation=None, output=None, review=None, cache=None):
    global ROOT, ORIGINAL_DIR, ORIGINAL_BIN, TRANSLATION, TEXT_DIR, GRAPHICS_CSV, HANDMADE, APPROVED
    global OUTPUT, REVIEW, JAPANESE_IMAGES, ENGLISH_IMAGES, COMPARE, CONTACT_SHEETS, EDIT_REFS
    global CACHE, GAME_FILES, UNPACKED, AUTO_RENDERS, BUILD_TMP
    ROOT = Path(root)

    original = Path(original) if original else ROOT / 'original-game'
    if original.suffix.lower() == '.bin':
        ORIGINAL_DIR, ORIGINAL_BIN = original.parent, original
    else:
        ORIGINAL_DIR = original
        found = sorted(original.glob('*.bin')) if original.is_dir() else []
        ORIGINAL_BIN = original / ORIGINAL_NAME if (original / ORIGINAL_NAME).exists() or len(found) != 1 \
            else found[0]

    TRANSLATION = Path(translation) if translation else ROOT / 'translation'
    TEXT_DIR = TRANSLATION / 'text'
    GRAPHICS_CSV = TRANSLATION / 'graphics.csv'
    HANDMADE = TRANSLATION / 'images-handmade'
    APPROVED = TRANSLATION / 'images-approved'

    OUTPUT = Path(output) if output else ROOT / 'output'

    REVIEW = Path(review) if review else ROOT / 'review'
    JAPANESE_IMAGES = REVIEW / 'images-japanese'
    ENGLISH_IMAGES = REVIEW / 'images-english'
    COMPARE = REVIEW / 'compare'
    CONTACT_SHEETS = REVIEW / 'contact-sheets'
    EDIT_REFS = REVIEW / 'edit'

    CACHE = Path(cache) if cache else ROOT / 'cache'
    GAME_FILES = CACHE / 'game-files'          # files extracted from the original disc
    UNPACKED = CACHE / 'unpacked'               # unpacked archives (unpacked/DATALINK/...)
    AUTO_RENDERS = CACHE / 'auto-renders'       # automatic renders (refreshed every build)
    BUILD_TMP = CACHE / 'build-tmp'             # scratch space for a build


_set()


def configure(argv):
    """Apply the folder options found in argv; returns the remaining arguments for the tool itself."""
    ap = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    for opt in ('root', 'original', 'translation', 'output', 'review', 'cache'):
        ap.add_argument(f'--{opt}')
    args, rest = ap.parse_known_args(argv)
    _set(**{k: v for k, v in vars(args).items() if v})
    return rest


def show(p):
    """A path for messages: relative to the current directory when it is inside it."""
    p = Path(p)
    try:
        return str(p.resolve().relative_to(Path.cwd()))
    except ValueError:
        return str(p)
